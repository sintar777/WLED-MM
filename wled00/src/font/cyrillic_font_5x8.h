inline bool normalizeCyrillicCodepoint(uint16_t codepoint, uint16_t &upperCodepoint) {
  if (codepoint == 0x0451) { // ё
    upperCodepoint = 0x0401;
    return true;
  }
  if (codepoint >= 0x0430 && codepoint <= 0x044F) { // а..я
    upperCodepoint = codepoint - 0x20;
    return true;
  }
  if (codepoint >= 0x0410 && codepoint <= 0x042F) { // А..Я
    upperCodepoint = codepoint;
    return true;
  }
  return false;
}

inline bool getCyrillicGlyph5x8(uint16_t codepoint, uint8_t outRows[8]) {
  uint16_t upperCodepoint = 0;
  if (!normalizeCyrillicCodepoint(codepoint, upperCodepoint)) return false;

  for (size_t i = 0; i < sizeof(cyrillicGlyphs5x8)/sizeof(cyrillicGlyphs5x8[0]); i++) {
    if (pgm_read_word_near(&cyrillicGlyphs5x8[i].codepoint) == upperCodepoint) {
      for (uint8_t r = 0; r < 8; r++) {
        outRows[r] = pgm_read_byte_near(&cyrillicGlyphs5x8[i].rows[r]);
      }
      return true;
    }
  }
  return false;
}
